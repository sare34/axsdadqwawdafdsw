package com.phoneguardian.security.data.remote

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

class GeminiApiClient(private val apiKeyProvider: () -> String) {

    private val client = OkHttpClient.Builder()
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .build()

    suspend fun analyzeThreat(anonymizedReport: String): Result<String> = withContext(Dispatchers.IO) {
        val key = apiKeyProvider()
        if (key.isBlank()) {
            return@withContext Result.failure(IllegalStateException("Gemini API key is not configured."))
        }

        try {
            val endpoint = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=$key"

            val prompt = """
                You are Phone Guardian AI, an autonomous cybersecurity analyst on Android.
                Review the following anonymized device security findings:
                $anonymizedReport
                
                Please provide:
                1. High-level threat assessment.
                2. Immediate autonomous/manual steps to mitigate.
                3. Risk severity ranking.
                
                Keep response concise, structured, and Arabic-friendly.
            """.trimIndent()

            val jsonBody = JSONObject().apply {
                val contentsArray = JSONArray().apply {
                    val contentObj = JSONObject().apply {
                        val partsArray = JSONArray().apply {
                            put(JSONObject().put("text", prompt))
                        }
                        put("parts", partsArray)
                    }
                    put(contentObj)
                }
                put("contents", contentsArray)
            }

            val request = Request.Builder()
                .url(endpoint)
                .post(jsonBody.toString().toRequestBody("application/json".toMediaType()))
                .build()

            val response = client.newCall(request).execute()
            if (!response.isSuccessful) {
                return@withContext Result.failure(Exception("Gemini HTTP ${response.code}: ${response.message}"))
            }

            val respBody = response.body?.string() ?: ""
            val parsedResponse = JSONObject(respBody)
            val candidates = parsedResponse.optJSONArray("candidates")
            if (candidates != null && candidates.length() > 0) {
                val first = candidates.getJSONObject(0)
                val content = first.getJSONObject("content")
                val parts = content.getJSONArray("parts")
                val replyText = parts.getJSONObject(0).getString("text")
                Result.success(replyText)
            } else {
                Result.failure(Exception("No analysis generated by Gemini"))
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    suspend fun chatWithAi(history: List<Pair<String, String>>, userMessage: String): Result<String> = withContext(Dispatchers.IO) {
        val key = apiKeyProvider()
        if (key.isBlank()) {
            return@withContext Result.failure(IllegalStateException("Gemini API key is missing."))
        }

        try {
            val endpoint = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=$key"

            val contentsArray = JSONArray()
            
            // System instructions context
            val systemContext = "You are Phone Guardian's AI Security Copilot. Answer cybersecurity queries concisely in Arabic (or user's preferred language). You never ask for or process personal data (SMS, photos, contacts)."
            
            val initialSys = JSONObject().apply {
                put("role", "user")
                put("parts", JSONArray().apply { put(JSONObject().put("text", systemContext)) })
            }
            val initialSysResp = JSONObject().apply {
                put("role", "model")
                put("parts", JSONArray().apply { put(JSONObject().put("text", "أهلاً بك. أنا حارس الهاتف الذكي (Phone Guardian). جاهز لتحليل أي مخاطر أمنية ومساعدتك في تأمين جهازك.")) })
            }
            contentsArray.put(initialSys)
            contentsArray.put(initialSysResp)

            for ((role, text) in history) {
                val item = JSONObject().apply {
                    put("role", if (role == "USER") "user" else "model")
                    put("parts", JSONArray().apply { put(JSONObject().put("text", text)) })
                }
                contentsArray.put(item)
            }

            val currentMsg = JSONObject().apply {
                put("role", "user")
                put("parts", JSONArray().apply { put(JSONObject().put("text", userMessage)) })
            }
            contentsArray.put(currentMsg)

            val jsonBody = JSONObject().apply {
                put("contents", contentsArray)
            }

            val request = Request.Builder()
                .url(endpoint)
                .post(jsonBody.toString().toRequestBody("application/json".toMediaType()))
                .build()

            val response = client.newCall(request).execute()
            if (!response.isSuccessful) {
                return@withContext Result.failure(Exception("Gemini HTTP ${response.code}: ${response.message}"))
            }

            val respBody = response.body?.string() ?: ""
            val parsedResponse = JSONObject(respBody)
            val candidates = parsedResponse.optJSONArray("candidates")
            if (candidates != null && candidates.length() > 0) {
                val first = candidates.getJSONObject(0)
                val content = first.getJSONObject("content")
                val parts = content.getJSONArray("parts")
                val replyText = parts.getJSONObject(0).getString("text")
                Result.success(replyText)
            } else {
                Result.failure(Exception("No response from AI"))
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
